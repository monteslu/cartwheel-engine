// Writes action2d's gate inputs from one recorded playthrough:
//   tests/action2d-pad.json          pad 0 + mouse (every host, romdev included)
//   tests/action2d-keys.json         the same play on the keyboard + mouse (romdev cannot inject keys)
//   tests/action2d-pad-control.json  / action2d-keys-control.json: the attack rebinding press
//                                    removed, so the hero never swings: must FAIL the gate
//   games/action2d/script.inc        the pad script compiled into action2d_auto
//
// The recording comes from the game's authoring bot (games/action2d/bot.c):
//   ACTION2D_BOT=$PWD/out/action2d-bot.json CW_FRAMES=4000 \
//     CW_ASSETS=build/native/games/action2d.assets build/native/games/action2d
//   node tests/action2d-script.mjs out/action2d-bot.json
// The bot plays from the game state each frame; the gates only replay its
// input, so every host must reproduce the same game exactly.
//
// Keyboard mapping (identical vectors and presses, so identical play):
//   axes lx/ly -1/+1 -> a/d, w/s (move)     north -> k (attack, after rebinding to it)
//   south -> return (menu accept)           start -> escape (pause)
//   d-pad -> arrow keys (menu navigation)   the mouse is passed through
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { enterGpuSandbox } from '../tools/lib/gpu-sandbox.mjs';
import { testEnv } from '../tools/lib/wgpu-pin.mjs';
await enterGpuSandbox(); // only the test GPU is visible, no desktop (tools/lib/gpu-sandbox.mjs)
testEnv(process.env); // what it starts renders offscreen and cannot reach the desktop

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) { console.error('usage: node tests/action2d-script.mjs <bot recording.json>'); process.exit(2); }
const rec = JSON.parse(readFileSync(src, 'utf8'));
const out = (name, data) => writeFileSync(join(ROOT, 'tests', name), JSON.stringify(data, null, 0).replace(/\},\{/g, '},\n{') + '\n');

// the rebinding capture press: the first north press (the prologue's), before any play
const captureIdx = rec.findIndex((e) => (e.buttons || []).includes('north'));
if (captureIdx < 0) throw new Error('recording has no rebinding press');
const withoutCapture = (r) => r.map((e, i) => (i === captureIdx ? { ...e, buttons: (e.buttons || []).filter((b) => b !== 'north') } : e));

const KEY = { south: 'return', north: 'k', start: 'escape', up: 'up', down: 'down', left: 'left', right: 'right' };
function toKeys(r) {
  return r.map((e) => {
    const keys = [];
    for (const b of e.buttons || []) {
      if (!KEY[b]) throw new Error(`no key for pad button ${b}`);
      keys.push(KEY[b]);
    }
    const ax = e.axes || {};
    if (ax.lx < 0) keys.push('a');
    if (ax.lx > 0) keys.push('d');
    if (ax.ly < 0) keys.push('w');
    if (ax.ly > 0) keys.push('s');
    for (const v of [ax.lx || 0, ax.ly || 0]) if (v !== 0 && Math.abs(v) !== 1) throw new Error('keyboard play needs digital axes');
    const k = { frame: e.frame };
    if (keys.length) k.keys = keys;
    if (e.mouse) k.mouse = e.mouse;
    return k;
  });
}

out('action2d-pad.json', rec);
out('action2d-pad-control.json', withoutCapture(rec));
out('action2d-keys.json', toKeys(rec));
out('action2d-keys-control.json', toKeys(withoutCapture(rec)));

const BITS = { south: 0, east: 1, west: 2, north: 3, back: 4, guide: 5, start: 6, l3: 7, r3: 8, l: 9, r: 10, up: 11, down: 12, left: 13, right: 14 };
const lines = rec.map((e) => {
  const b = (e.buttons || []).reduce((m, n) => m | (1 << BITS[n]), 0);
  const ax = e.axes || {}, m = e.mouse;
  const mb = m && m.buttons && m.buttons.includes('left') ? 1 : 0;
  return `  { ${e.frame}, ${b}u, ${(ax.lx || 0).toFixed(1)}f, ${(ax.ly || 0).toFixed(1)}f, ${m ? m.x : -1}, ${m ? m.y : -1}, ${mb}u },`;
});
writeFileSync(join(ROOT, 'games/action2d/script.inc'),
  '/* generated by tests/action2d-script.mjs from tests/action2d-pad.json (do not edit) */\n' + lines.join('\n') + '\n');
console.log(`wrote ${rec.length} entries; last frame ${rec[rec.length - 1].frame}`);
