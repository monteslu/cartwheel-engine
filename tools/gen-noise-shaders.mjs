// The GPU ports of cw_noise (cartwheel/noise.h) as C strings: src/noise/noise.glsl
// and src/noise/noise.wgsl with FastNoiseLite's tables (gradients, cell
// offsets) read from the vendored header and written as exact float32 values,
// into src/noise/noise_shaders.c (generated, committed).
//
//   node tools/gen-noise-shaders.mjs           write src/noise/noise_shaders.c
//   node tools/gen-noise-shaders.mjs --check   exit 1 when it is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fnl = readFileSync(join(ROOT, 'src/third_party/fastnoiselite/FastNoiseLite.h'), 'utf8');

/** A float table of the header as float32 values. */
function table(name, count) {
  const m = fnl.match(new RegExp(`static const float ${name}\\[\\] =\\s*\\{([^}]*)\\}`));
  if (!m) throw new Error(`FastNoiseLite.h: no table ${name}`);
  const v = m[1].split(',').map((s) => s.trim()).filter(Boolean).map((s) => Math.fround(parseFloat(s.replace(/f$/, ''))));
  if (v.length !== count) throw new Error(`${name}: ${v.length} values, expected ${count}`);
  // 9 significant digits round-trip every float32
  return v.map((x) => {
    const s = x.toPrecision(9);
    if (Math.fround(parseFloat(s)) !== x) throw new Error(`${name}: ${x} does not round-trip`);
    return s.includes('e') || s.includes('.') ? s : s + '.0';
  });
}

const tabs = [['CWN_G2D', 'GRADIENTS_2D', 256], ['CWN_R2D', 'RAND_VECS_2D', 512], ['CWN_G3D', 'GRADIENTS_3D', 256],
  ['CWN_R3D', 'RAND_VECS_3D', 1024]].map(([n, src, c]) => ({ n, c, v: table(src, c) }));

const wrap = (v) => {
  const out = [];
  for (let i = 0; i < v.length; i += 8) out.push('  ' + v.slice(i, i + 8).join(', '));
  return out.join(',\n');
};
const glslTables = tabs.map((t) => `const float ${t.n}[${t.c}] = float[${t.c}](\n${wrap(t.v)});`).join('\n');
const wgslTables = tabs.map((t) => `const ${t.n} = array<f32, ${t.c}>(\n${wrap(t.v)});`).join('\n');

const src = (file, tables) => readFileSync(join(ROOT, 'src/noise', file), 'utf8').replace('@TABLES@', tables);
const cstr = (s) => s.split('\n').map((l) => '  "' + l.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '\\n"').join('\n');

const out = `/* GENERATED by tools/gen-noise-shaders.mjs from src/noise/noise.glsl,
 * src/noise/noise.wgsl and FastNoiseLite's tables: do not edit. */
#include "cartwheel/noise.h"

static const char GLSL[] =
${cstr(src('noise.glsl', glslTables))};

static const char WGSL[] =
${cstr(src('noise.wgsl', wgslTables))};

const char *cw_noise_glsl(void) { return GLSL; }
const char *cw_noise_wgsl(void) { return WGSL; }
`;

const dst = join(ROOT, 'src/noise/noise_shaders.c');
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(dst, 'utf8'); } catch {}
  if (cur !== out) {
    console.error('src/noise/noise_shaders.c is stale: run node tools/gen-noise-shaders.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(dst, out);
}
