// Reference results for cw_ccdik_solve from three.js r186's own CCDIKSolver.
//
//   node tools/gen-ccdik-fixture.mjs <three r186 package dir>   (npm three@0.186.x)
//
// Runs CCDIKSolver.update on a seven-bone chain (root, four links, the
// effector, a target bone under the root) for several chain settings and
// targets, and writes tests/unit/ccdik_r186.h: the starting pose, each case's
// settings and the links' quaternions three.js produced. tests/unit/test_ik.c
// replays every case through cw_ccdik_solve and compares (the tolerance
// covers three.js's double Math.acos vs float cw_acos).
import { writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/gen-ccdik-fixture.mjs <three r186 package dir>');
  process.exit(2);
}
const THREE = await import(pathToFileURL(join(dir, 'build/three.module.js')).href);
const { CCDIKSolver } = await import(pathToFileURL(join(dir, 'examples/jsm/animation/CCDIKSolver.js')).href);
if (THREE.REVISION !== '186') {
  console.error(`three.js r${THREE.REVISION}: the fixture must come from r186`);
  process.exit(1);
}

// the chain: bone 0 root, 1..4 links, 5 effector, 6 target (child of root)
const parent = [-1, 0, 1, 2, 3, 4, 0];
const pos = [[0, 0, 0], [0, 0.5, 0], [0, 1, 0], [0, 0.8, 0], [0, 0.6, 0], [0, 0.4, 0], [0, 0, 0]];
const f = (x) => Math.fround(x);
const rotEuler = [[0, 0, 0], [0.1, 0, 0.2], [0.15, -0.1, 0.05], [-0.2, 0.3, 0.1], [0.05, 0.1, -0.15], [0, 0, 0], [0, 0, 0]];
const rot = rotEuler.map((e) => {
  const q = new THREE.Quaternion().setFromEuler(new THREE.Euler(e[0], e[1], e[2]));
  return [f(q.x), f(q.y), f(q.z), f(q.w)];
});

const targets = [[1.2, 1.5, 0.3], [-0.8, 2.2, -0.6], [0.2, 0.6, 1.4], [2.5, 2.5, 2.5], [0.0, 3.2, 0.1]];
const cases = [
  { name: 'plain', iteration: 10 },
  { name: 'one-iteration' },
  { name: 'limits', iteration: 8, limitation: { 3: [1, 0, 0] }, rotationMin: { 2: [-0.5, -0.4, -0.6] }, rotationMax: { 2: [0.5, 0.4, 0.6] } },
  { name: 'angles', iteration: 6, minAngle: 0.0, maxAngle: 0.2 },
  { name: 'blend', iteration: 10, blendFactor: 0.5 },
  { name: 'disabled', iteration: 10, disabled: 2 },
];

const out = [];
for (const c of cases) {
  for (const t of targets) {
    const bones = parent.map(() => new THREE.Bone());
    bones.forEach((b, i) => {
      b.position.set(...pos[i]);
      b.quaternion.set(...rot[i]);
      if (parent[i] >= 0) bones[parent[i]].add(b);
    });
    bones[6].position.set(...t.map(f));
    const mesh = new THREE.SkinnedMesh(new THREE.BufferGeometry(), new THREE.MeshBasicMaterial());
    mesh.add(bones[0]);
    mesh.bind(new THREE.Skeleton(bones));
    mesh.updateMatrixWorld(true);
    const links = [4, 3, 2, 1].map((index) => {
      const l = { index };
      if (c.limitation?.[index]) l.limitation = new THREE.Vector3(...c.limitation[index]);
      if (c.rotationMin?.[index]) l.rotationMin = new THREE.Vector3(...c.rotationMin[index]);
      if (c.rotationMax?.[index]) l.rotationMax = new THREE.Vector3(...c.rotationMax[index]);
      if (c.disabled === index) l.enabled = false;
      return l;
    });
    const ik = { target: 6, effector: 5, links };
    if (c.iteration !== undefined) ik.iteration = c.iteration;
    if (c.minAngle !== undefined) ik.minAngle = c.minAngle;
    if (c.maxAngle !== undefined) ik.maxAngle = c.maxAngle;
    if (c.blendFactor !== undefined) ik.blendFactor = c.blendFactor;
    new CCDIKSolver(mesh, [ik]).update();
    out.push({ c, t, ik, q: [1, 2, 3, 4].map((i) => bones[i].quaternion.toArray()) });
  }
}

const num = (x) => {
  const s = Math.fround(x).toPrecision(9);
  return s.includes('e') || s.includes('.') ? `${s}f` : `${s}.0f`;
};
const v3 = (v) => `{ ${v.map(num).join(', ')} }`;
const lines = [];
lines.push('/* Generated by tools/gen-ccdik-fixture.mjs from three.js r186 CCDIKSolver: do not edit. */');
lines.push('#define CCD_BONES 7');
lines.push(`static const int ccd_parent[CCD_BONES] = { ${parent.join(', ')} };`);
lines.push(`static const float ccd_pos[CCD_BONES][3] = { ${pos.map(v3).join(', ')} };`);
lines.push(`static const float ccd_rot[CCD_BONES][4] = { ${rot.map(v3).join(', ')} };`);
lines.push('typedef struct ccd_case {');
lines.push('  float target[3];');
lines.push('  int iteration; int has_min, has_max; float min_angle, max_angle; int has_blend; float blend;');
lines.push('  int limitation_link; float limitation[3];');
lines.push('  int rot_link; float rot_min[3], rot_max[3];');
lines.push('  int disabled_link;');
lines.push('  float q[4][4]; /* links 1..4 after the solve */');
lines.push('} ccd_case;');
lines.push(`#define CCD_CASES ${out.length}`);
lines.push('static const ccd_case ccd_cases[CCD_CASES] = {');
for (const { c, t, q } of out) {
  const lim = c.limitation ? Object.entries(c.limitation)[0] : null;
  const rm = c.rotationMin ? Object.entries(c.rotationMin)[0] : null;
  const rx = c.rotationMax ? Object.entries(c.rotationMax)[0] : null;
  lines.push(`  { ${v3(t)}, ${c.iteration ?? 0}, ${c.minAngle !== undefined ? 1 : 0}, ${c.maxAngle !== undefined ? 1 : 0}, ` +
    `${num(c.minAngle ?? 0)}, ${num(c.maxAngle ?? 0)}, ${c.blendFactor !== undefined ? 1 : 0}, ${num(c.blendFactor ?? 1)},\n` +
    `    ${lim ? lim[0] : -1}, ${v3(lim ? lim[1] : [0, 0, 0])}, ${rm ? rm[0] : -1}, ${v3(rm ? rm[1] : [0, 0, 0])}, ` +
    `${v3(rx ? rx[1] : [0, 0, 0])}, ${c.disabled ?? -1},\n    { ${q.map(v3).join(', ')} } }, /* ${c.name} */`);
}
lines.push('};');
writeFileSync(join(ROOT, 'tests/unit/ccdik_r186.h'), lines.join('\n') + '\n');
console.log(`tests/unit/ccdik_r186.h: ${out.length} cases`);
