/* editor_import: the end-to-end import test, "drag a glTF in, see it imported,
 * place it", played inside the editor on every host (native, romdev,
 * Chromium, wasmcart-native) with no outside driver:
 *   - a CC0 glTF (editor/tests/import: lantern.gltf + .bin + .png, made by
 *     gen-assets.mjs) is copied into the project as a CWVFS1 archive through
 *     cw_vfs_import: natively onto disk (CW_PROJECT), in a cart into the
 *     in-memory project layer;
 *   - it shows up in the FileSystem panel, imports through cwpack's
 *     importer, and gets a thumbnail;
 *   - the pointer (injected as raw input, the same path a mouse takes)
 *     drags its thumbnail onto the Preview panel: the drop places it on the
 *     ground there; a second copy is placed with the fs.place command;
 *   - the texture is renamed into a sub-folder (the .gltf's URI follows),
 *     a delete of a used file is refused, a corrupt glTF fails to import
 *     with a clear message;
 *   - the scene is saved, closed and opened again, and both placed lanterns
 *     render (pixels they cover in the scene camera's view).
 * Debug fields carry every result; tests/editor-import.mjs compares hosts
 * and runs the controls. CW_IMPORT_STOP=<frame> stops the session early (a
 * control). */
#include <stdlib.h>
#include <string.h>

#include "cartwheel/debug.h"
#include "cartwheel/gpu.h"
#include "cartwheel/resource.h"
#include "cartwheel/vfs.h"
#include "../core/internal.h"

/* the embedded test files (generated by editor/CMakeLists.txt from editor/tests/import) */
typedef struct { const char *name; const unsigned char *data; unsigned len; } embedded;
extern const embedded cwed_import_files[];
extern const int cwed_import_file_count;

static int g_argc;
static char **g_argv;

typedef struct { int frame; const char *line; } step;
static const step SESSION[] = {
  { 2, "@copy lantern.gltf lantern.bin lantern_paint.png" },
  { 3, "panel.show id=filesystem" },
  { 3, "panel.show id=import" },
  { 3, "panel.show id=preview" },
  { 4, "fs.select path=models/lantern.gltf" },
  { 24, "@press models/lantern.gltf" },
  { 25, "@move 14 6" },
  { 26, "@move_preview 0.62 0.8" },
  { 28, "@release" },
  { 30, "fs.place file=models/lantern.gltf parent=Props position=\"vec3(-2.4, 0, 1.2)\" name=LanternB" },
  { 31, "fs.delete path=models/lantern_paint.png" }, /* must fail: lantern.gltf uses it */
  { 32, "fs.rename from=models/lantern_paint.png to=models/paint/lantern_paint.png" },
  { 33, "@copy broken.gltf" },
  { 34, "fs.select path=models/broken.gltf" },
  { 38, "scene.save" },
  { 39, "scene.close" },
  { 40, "scene.open path=main.cwscene" },
  { 41, "@check" },
  { 42, "fs.select path=models/lantern.gltf" },
};

static int next_step, stop_frame = 1 << 30;
static int32_t done, failed, copied, listed, drag_ok, cmd_ok, reload_ok, rename_ok, refused_ok, broken_ok, px_drag, px_cmd,
    px_hidden, thumb_ok, import_ok_lantern;
static uint32_t reply_hash = CW_HASH32_INIT, broken_hash;

/* the injected pointer (logical window pixels), applied by the raw input filter */
static struct { bool on; float x, y; uint32_t buttons, pressed; } ptr;
static void input_filter(cw_raw_input *in, uint64_t frame, void *user) {
  (void)frame, (void)user;
  if (!ptr.on) return;
  in->mouse_present = true;
  in->mouse_x = ptr.x;
  in->mouse_y = ptr.y;
  in->mouse_buttons = ptr.buttons;
  in->mouse_pressed = ptr.pressed;
  ptr.pressed = 0;
}

static const embedded *file_named(const char *n) {
  for (int i = 0; i < cwed_import_file_count; i++)
    if (!strcmp(cwed_import_files[i].name, n)) return &cwed_import_files[i];
  return NULL;
}

/* bring files into the project the way an archive import does (vfs import) */
static void copy_in(const char *names) {
  CW_ARRAY(char) a = { 0 };
  const char *hdr = "CWVFS1\n";
  for (const char *h = hdr; *h; h++) cw_array_push(&a, *h);
  char buf[256];
  snprintf(buf, sizeof buf, "%s", names);
  for (char *n = strtok(buf, " "); n; n = strtok(NULL, " ")) {
    const embedded *f = file_named(n);
    if (!f) { failed++; continue; }
    const char *head = cw_frame_printf("models/%s\n%u\n", n, f->len);
    for (const char *h = head; *h; h++) cw_array_push(&a, *h);
    for (unsigned i = 0; i < f->len; i++) cw_array_push(&a, (char)f->data[i]);
  }
  if (cw_vfs_import(a.data, (size_t)a.count)) copied++;
  else failed++;
  cw_array_free(&a);
}

static int json_int(const char *j, const char *key) {
  const char *k = j ? strstr(j, cw_frame_printf("\"%s\":", key)) : NULL;
  return k ? atoi(k + strlen(key) + 3) : -1;
}

static bool run_line(const char *line) {
  char *json = NULL;
  bool ok = cwed_run(line, &json);
  if (json) reply_hash = cw_hash32(json, strlen(json), reply_hash), cw_free(json);
  return ok;
}

static int node_pixels(const char *path) {
  char *j = NULL;
  int px = cwed_run(cw_frame_printf("preview.node_pixels path=%s width=320 height=180", cwed_quote(path)), &j) ? json_int(j, "pixels") : -1;
  cw_free(j);
  return px;
}

/* a placed lantern: a MeshInstance3D whose mesh is the glTF's UID */
static bool is_lantern(const char *path) {
  cwed_doc *d = cwed_doc_active();
  cw_node n = d ? cwed_doc_node(d, path) : (cw_node){ 0 };
  if (CW_HANDLE_IS_NULL(n) || !cw_node_is(n, "MeshInstance3D")) return false;
  cw_value v;
  return cw_node_get_prop(n, "mesh", &v) && v.type == CW_T_RES && v.res && cw_res_index_path(v.res) &&
         !strcmp(cw_res_index_path(v.res), "models/lantern.gltf");
}

static void check(void) {
  reload_ok = is_lantern("lantern") && is_lantern("Props/LanternB");
  px_drag = node_pixels("lantern");
  px_cmd = node_pixels("Props/LanternB");
  /* control for the pixel check: a hidden node covers nothing */
  run_line("node.set path=Props/LanternB prop=visible value=false");
  px_hidden = node_pixels("Props/LanternB");
  run_line("edit.undo");
  /* the rename moved the texture and the glTF follows it */
  char *j = NULL;
  cwed_run("fs.deps path=models/paint/lantern_paint.png", &j);
  rename_ok = j && strstr(j, "\"used_by\":[\"models/lantern.gltf\"]") && !cw_vfs_exists("models/lantern_paint.png");
  cw_free(j);
  char *t = cw_vfs_read("models/lantern.gltf", NULL);
  rename_ok = rename_ok && t && strstr(t, "\"paint/lantern_paint.png\"");
  free(t);
  /* the corrupt glTF: a clear import error */
  j = NULL;
  cwed_run("import.info path=models/broken.gltf", &j);
  const char *e = j ? strstr(j, "\"error\":\"") : NULL;
  broken_ok = e && strstr(e, "accessor 0 reads past its data");
  if (e) broken_hash = cw_hash32(e, strlen(e), CW_HASH32_INIT);
  cw_free(j);
  j = NULL;
  cwed_run("import.info path=models/lantern.gltf", &j);
  import_ok_lantern = j && strstr(j, "\"status\":\"ok\"") && strstr(j, "168 triangles");
  cw_free(j);
  j = NULL;
  cwed_run("preview.get path=models/lantern.gltf", &j);
  thumb_ok = j && strstr(j, "\"ready\":true") && json_int(j, "texture") != 0;
  const char *cov = j ? strstr(j, "\"coverage\":") : NULL;
  if (cov && atof(cov + 11) < 0.05) thumb_ok = 0; /* an empty thumbnail is not a preview */
  cw_free(j);
}

static void session_step(void) {
  int f = (int)cw_frame_index();
  if (f >= stop_frame) return;
  while (next_step < (int)CW_ARRAY_LEN(SESSION) && SESSION[next_step].frame <= f) {
    const char *l = SESSION[next_step++].line;
    if (!strncmp(l, "@copy ", 6)) {
      copy_in(l + 6);
      const cw_vfs_entry *e;
      int n = cw_vfs_list_dir("models", 0, &e);
      listed = 0;
      for (int i = 0; i < n; i++) listed += !strcmp(e[i].name, "lantern.gltf");
    } else if (!strncmp(l, "@press ", 7)) {
      char *j = NULL;
      if (!cwed_run(cw_frame_printf("fs.cell path=%s", l + 7), &j)) failed++;
      ptr.on = true;
      ptr.x = (float)json_int(j, "x");
      ptr.y = (float)json_int(j, "y");
      ptr.buttons = ptr.pressed = 1;
      cw_free(j);
    } else if (!strncmp(l, "@move ", 6)) {
      float dx, dy;
      sscanf(l + 6, "%f %f", &dx, &dy);
      ptr.x += dx, ptr.y += dy;
    } else if (!strncmp(l, "@move_preview ", 14)) {
      float fx, fy;
      sscanf(l + 14, "%f %f", &fx, &fy);
      cw_node view = cw_node_get(cwed_panel_content("preview"), "View");
      cw_rect r = cw_control_global_rect(cw_node_valid(view) ? view : cwed_panel_content("preview"));
      ptr.x = r.x + r.w * fx;
      ptr.y = r.y + r.h * fy;
    } else if (!strcmp(l, "@release")) {
      ptr.buttons = 0;
    } else if (!strcmp(l, "@check")) {
      check();
    } else {
      bool ok = run_line(l);
      if (!ok) {
        failed++;
        if (!strncmp(l, "fs.delete", 9)) refused_ok = 1; /* the reference check refused it */
      }
    }
  }
  /* the drop happened: a lantern on the ground */
  if (!drag_ok && is_lantern("lantern")) drag_ok = 1;
  if (!cmd_ok && is_lantern("Props/LanternB")) cmd_ok = 1;
  if (next_step == (int)CW_ARRAY_LEN(SESSION)) done = 1;
}

static void init(void *u) {
  (void)u;
  if (getenv("CW_IMPORT_STOP")) stop_frame = atoi(getenv("CW_IMPORT_STOP"));
  cwed_init(g_argc, g_argv);
  cwed_debug_fields();
  cw_ui_debug_register("ui");
  cw_set_raw_input_filter(input_filter, NULL);
  cw_debug_i32("session.done", &done);
  cw_debug_i32("session.failed", &failed);
  cw_debug_u32("session.reply_hash", &reply_hash);
  cw_debug_i32("import_test.copied", &copied);
  cw_debug_i32("import_test.listed", &listed);
  cw_debug_i32("import_test.import_ok", &import_ok_lantern);
  cw_debug_i32("import_test.thumb_ok", &thumb_ok);
  cw_debug_i32("import_test.drag_placed", &drag_ok);
  cw_debug_i32("import_test.cmd_placed", &cmd_ok);
  cw_debug_i32("import_test.refused_delete", &refused_ok);
  cw_debug_i32("import_test.rename_ok", &rename_ok);
  cw_debug_i32("import_test.broken_error", &broken_ok);
  cw_debug_u32("import_test.broken_hash", &broken_hash);
  cw_debug_i32("import_test.reload_ok", &reload_ok);
  cw_debug_i32("import_test.pixels_drag", &px_drag);
  cw_debug_i32("import_test.pixels_cmd", &px_cmd);
  cw_debug_i32("import_test.pixels_hidden", &px_hidden);
}

void cwed__fields_frame(void);

static void update(void *u, double dt) {
  (void)u;
  session_step();
  cwed_frame(dt);
  cwed__fields_frame();
}

static void render(void *u, double a) {
  (void)u, (void)a;
  cw_gpu_clear_window(0.1f, 0.11f, 0.13f, 1);
  cw_ui_render(cwed_ui_tree());
}

static void shutdown(void *u) {
  (void)u;
  cwed_shutdown();
}

cw_app_desc cw_main(int argc, char **argv) {
  g_argc = argc;
  g_argv = argv;
  return (cw_app_desc){ .title = "cartwheel editor (import test)", .width = 1280, .height = 720, .render_scale = 1, .init = init, .update = update,
                        .render = render, .shutdown = shutdown, .debug = true };
}
