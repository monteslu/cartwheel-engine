// ── the room: 30 x 17 cells seen from above, three map layers ────────────────────────────────────────────
// The cells name each terrain by its first tile (floor 12, wall 16, moss 127: the whole tile, fence 128); the
// scene's autotile picks every cell's tile from its neighbours as it loads.
const RW = 30, RH = 17, FLOOR = 12, WALL = 16, MOSS = 127, FENCE = 128;
const layer = () => Array.from({ length: RH }, () => new Array(RW).fill(-1));
const ground = layer(), moss = layer(), walls = layer();
const box = (g2, x0, x1, y0, y1, id) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) g2[y][x] = id; };
box(ground, 0, RW - 1, 0, RH - 1, FLOOR);
box(walls, 0, RW - 1, 0, 0, WALL); box(walls, 0, RW - 1, RH - 1, RH - 1, WALL);
box(walls, 0, 0, 0, RH - 1, WALL); box(walls, RW - 1, RW - 1, 0, RH - 1, WALL);
box(walls, 14, 15, 1, RH - 2, WALL);          // the wall between the two chambers
box(walls, 14, 15, 3, 4, -1);                 // the upper doorway
box(walls, 14, 15, 12, 13, -1);               // the lower doorway
box(walls, 6, 7, 6, 7, WALL);                 // pillars
box(walls, 22, 23, 12, 13, WALL);
box(walls, 4, 4, 11, 13, WALL);               // a stub and an L
box(walls, 9, 11, 10, 10, WALL); box(walls, 11, 11, 11, 12, WALL);
box(walls, 18, 24, 8, 8, FENCE);              // a fence with a branch
box(walls, 21, 21, 5, 7, FENCE);
box(moss, 2, 4, 2, 4, MOSS);                  // moss patches (the corner set grows a ring of transitions round each)
box(moss, 8, 11, 13, 14, MOSS);
box(moss, 18, 19, 2, 2, MOSS); box(moss, 25, 27, 10, 13, MOSS);

