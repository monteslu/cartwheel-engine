// Generates the tiles2d sample's scenes from maps painted here, so the cells text is never typed by hand.
//   node samples/tiles2d/make-level.mjs
// Writes assets/strip.cwscene: a side-scroller strip with slopes, one-way planks, half blocks and a ledge
// the sample removes in play.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = join(dirname(fileURLToPath(import.meta.url)), 'assets');
const STONE = 1, GRASS = 2, DIRT = 3, BRICK = 4, UP = 5, DOWN = 6, RISE_LO = 7, RISE_HI = 8, PLANK = 9, HALF = 10, WEDGE = 11;

/** rows of cells -> the TileMap2D text form, runs of 3 or more written "id*count" */
function cellsText(grid) {
  return grid.map(row => {
    let end = row.length;
    while (end > 0 && row[end - 1] < 0) end--;
    const out = [];
    for (let x = 0; x < end;) {
      let run = 1;
      while (x + run < end && row[x + run] === row[x]) run++;
      const c = row[x] < 0 ? '.' : String(row[x]);
      if (run > 2) out.push(`${c}*${run}`); else for (let k = 0; k < run; k++) out.push(c);
      x += run;
    }
    return out.length ? out.join(' ') : '.';
  }).join(' / ');
}

// ── the strip: 60 x 17 cells, the ground's top at row 13 ─────────────────────────────────────────────────
const SW = 60, SH = 17, GY = 13;
const g = Array.from({ length: SH }, () => new Array(SW).fill(-1));
const put = (x, y, id) => { g[y][x] = id; };
const fill = (x0, x1, y0, y1, id) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) put(x, y, id); };
fill(0, SW - 1, GY, GY, GRASS);
fill(0, SW - 1, GY + 1, SH - 1, DIRT);
fill(0, 0, 0, GY - 1, BRICK);
fill(SW - 1, SW - 1, 0, GY - 1, BRICK);
// a gentle rise onto a low plateau, and a slope back down
put(10, 12, RISE_LO); put(11, 12, RISE_HI);
fill(12, 17, 12, 12, GRASS);
put(18, 12, DOWN);
fill(10, 18, GY, GY, DIRT);
// planks: up two, down one
fill(21, 24, 10, 10, PLANK);
fill(25, 28, 7, 7, PLANK);
fill(29, 33, 10, 10, PLANK);
// a steep hill two cells high, ending in a cliff
put(34, 12, UP);
put(35, 11, UP); put(35, 12, DIRT);
fill(36, 41, 11, 11, GRASS);
fill(36, 41, 12, 12, DIRT);
fill(34, 41, GY, GY, DIRT);
// steps of half blocks, then wedges hanging from a stone beam
put(45, 12, HALF); put(46, 12, HALF);
fill(48, 53, 8, 8, STONE);
put(49, 9, WEDGE); put(51, 9, WEDGE);
// the ledge the sample takes away under a crate
fill(54, 56, 10, 10, STONE);

const strip = `[scene format=1]

; generated by samples/tiles2d/make-level.mjs: edit the map there
[node name="Strip" type="Node2D"]

[node name="Settings" parent="." type="CanvasSettings"]
virtual_width = 480
virtual_height = 270
scale_mode = FIT
clear_color = color(0.36, 0.56, 0.78, 1)
pixel_snap = true

[node name="Map" parent="." type="TileMap2D"]
tileset = "images/tiles.png"
tile_shapes = "1-4: full; 5: slope 0 16; 6: slope 16 0; 7: slope 0 8; 8: slope 8 16; 9: oneway; 10: rect 0 8 16 8; 11: poly 0 0, 16 0, 8 16"
tile_data = "sound: 1=stone, 4=stone, 10=stone, 2-3=earth, 5-8=earth, 9=wood; slip: 5-6=1"
cells0 = "${cellsText(g)}"

[node name="Solid" parent="Map" type="TileCollision2D"]
one_way_layer = 2
friction = 0.8

[node name="Hero" parent="." type="TileHero"]
position = vec2(40, 196)
collision_layer = 1
one_way_mask = 4
step_height = 9

[node name="Shape" parent="Hero" type="CollisionShape2D"]
shape = CAPSULE
radius = 6
height = 24

[node name="Body" parent="Hero" type="Polygon2D"]
polygon = "-6 -12, 6 -12, 6 12, -6 12"
color = color(0.96, 0.78, 0.26, 1)

[node name="Eye" parent="Hero" type="Polygon2D"]
polygon = "1 -8, 5 -8, 5 -4, 1 -4"
color = color(0.12, 0.12, 0.2, 1)

[node name="Camera" parent="Hero" type="Camera2D"]
current = true
smoothing = true
smoothing_speed = 6
limit_left = 0
limit_top = 0
limit_right = ${SW * 16}
limit_bottom = ${SH * 16}
${[['CrateA', 800, 110], ['CrateB', 424, 100], ['CrateC', 880, 150]].map(([name, x, y]) => `
[node name="${name}" parent="." type="RigidBody2D"]
position = vec2(${x}, ${y})
friction = 0.7

[node name="Shape" parent="${name}" type="CollisionShape2D"]
shape = RECT
size = vec2(12, 12)

[node name="Look" parent="${name}" type="Polygon2D"]
polygon = "-6 -6, 6 -6, 6 6, -6 6"
color = color(0.72, 0.5, 0.28, 1)

[node name="Band" parent="${name}" type="Polygon2D"]
polygon = "-6 -1, 6 -1, 6 1, -6 1"
color = color(0.42, 0.27, 0.14, 1)
`).join('')}`;
writeFileSync(join(DIR, 'strip.cwscene'), strip);
console.log('wrote', join(DIR, 'strip.cwscene'));
