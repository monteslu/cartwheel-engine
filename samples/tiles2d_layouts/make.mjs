function cellsText(grid) {
  return grid.map(row => {
    const out = [];
    for (let x = 0; x < row.length;) {
      let run = 1;
      while (x + run < row.length && row[x + run] === row[x]) run++;
      const c = row[x] < 0 ? '.' : String(row[x]);
      if (run > 2) out.push(`${c}*${run}`); else for (let k = 0; k < run; k++) out.push(c);
      x += run;
    }
    return out.join(' ');
  }).join(' / ');
}

/** an island W x H: water round the rim, rocks in a wall with one gap, sand and grass inside */
function island(W, H) {
  const g = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => ((x * 7 + y * 13) % 5 === 0 ? 1 : 0)));
  for (let x = 0; x < W; x++) { g[0][x] = 3; g[H - 1][x] = 3; }
  for (let y = 0; y < H; y++) { g[y][0] = 3; g[y][W - 1] = 3; }
  const wx = W >> 1;
  for (let y = 1; y < H - 1; y++) if (y !== H - 3) g[y][wx] = 2;   // a wall with a gap near the bottom
  return g;
}
