// Generates the tiles2d_layouts sample: its tile sets (CC0: made here, from code) and its scene.
//   node samples/tiles2d_layouts/make.mjs
// Writes assets/images/iso.png (32x16 diamonds), hexr.png (28x32 pointy-top hexagons), hexc.png (32x28
// flat-top hexagons), each a row of: 0 grass, 1 sand, 2 rock (solid), 3 water (solid); and assets/main.cwscene:
// one map of each layout, each with a TileCollision2D, a NavigationRegion2D and two walkers.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writePng } from '../../tools/lib/png.mjs';
import { rng } from '../../tools/lib/rng.mjs';

const DIR = join(dirname(fileURLToPath(import.meta.url)), 'assets');
const LOOKS = [[[70, 150, 78], [104, 190, 96]], [[196, 178, 120], [224, 206, 150]], [[98, 102, 122], [150, 154, 176]], [[40, 96, 170], [70, 140, 214]]];
const mix = (a, b, t) => a.map((v, i) => Math.round(v + (b[i] - v) * t));

/** a row of four tiles w x h, each pixel kept where inside(x, y) (0..1 coordinates of the pixel's middle) */
function sheet(file, w, h, inside, edge) {
  const px = new Uint8Array(4 * w * h * 4);
  LOOKS.forEach(([lo, hi], id) => {
    const r = rng(100 + id);
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      const u = (x + 0.5) / w, v = (y + 0.5) / h;
      if (!inside(u, v)) continue;
      let c = mix(lo, hi, r());
      if (edge(u, v)) c = mix(c, [20, 24, 36], id >= 2 ? 0.55 : 0.3);   // a darker rim, stronger on solid tiles
      else if (id === 2 && v < 0.45) c = mix(c, [220, 224, 236], 0.35);  // rock: a lit top
      const i = 4 * (y * 4 * w + id * w + x);
      px[i] = c[0]; px[i + 1] = c[1]; px[i + 2] = c[2]; px[i + 3] = 255;
    }
  });
  writePng(join(DIR, 'images', file), 4 * w, h, px);
}
const diamond = (u, v) => Math.abs(u - 0.5) + Math.abs(v - 0.5);
sheet('iso.png', 32, 16, (u, v) => diamond(u, v) <= 0.5, (u, v) => diamond(u, v) > 0.42);
// a pointy-top hexagon in its box: |u - 1/2| <= 1/2, and the four slanted sides
const hexr = (u, v) => Math.max(Math.abs(u - 0.5) * 2, Math.abs(v - 0.5) * 2 - (0.5 - Math.abs(u - 0.5)) );
const inHexR = (u, v) => { const a = Math.abs(u - 0.5), b = Math.abs(v - 0.5); return a <= 0.5 && b <= 0.5 - a * 0.5; };
const rimHexR = (u, v) => { const a = Math.abs(u - 0.5), b = Math.abs(v - 0.5); return a > 0.44 || b > 0.5 - a * 0.5 - 0.05; };
sheet('hexr.png', 28, 32, inHexR, rimHexR);
sheet('hexc.png', 32, 28, (u, v) => inHexR(v, u), (u, v) => rimHexR(v, u));
